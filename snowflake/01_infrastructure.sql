CREATE WAREHOUSE IF NOT EXISTS COMPUTE_WH
    WAREHOUSE_SIZE = 'X-SMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE;

CREATE RESOURCE MONITOR IF NOT EXISTS project_budget_guard
    WITH CREDIT_QUOTA = 100
    FREQUENCY = MONTHLY
    START_TIMESTAMP = IMMEDIATELY
    TRIGGERS
        ON 80 PERCENT DO NOTIFY
        ON 95 PERCENT DO SUSPEND
        ON 100 PERCENT DO SUSPEND_IMMEDIATE;

ALTER WAREHOUSE COMPUTE_WH SET
    RESOURCE_MONITOR = project_budget_guard;

CREATE DATABASE IF NOT EXISTS EURO_URBAN_DW;
CREATE SCHEMA IF NOT EXISTS EURO_URBAN_DW.BRONZE_RAW;

CREATE FILE FORMAT IF NOT EXISTS EURO_URBAN_DW.BRONZE_RAW.parquet_format
    TYPE = PARQUET
    COMPRESSION = AUTO;

CREATE STAGE IF NOT EXISTS EURO_URBAN_DW.BRONZE_RAW.overture_s3_stage
    URL = 's3://overturemaps-us-west-2/release/2026-08-19.0/'
    FILE_FORMAT = EURO_URBAN_DW.BRONZE_RAW.parquet_format;
